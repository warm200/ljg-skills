#!/usr/bin/env python3
"""Point every ljg-* skill at the user's NAS memory vault instead of local note folders.

Idempotent: run it after every upstream sync. It
  1. copies scripts/nas/NAS_NOTES.md into each skill directory,
  2. inserts (or refreshes) a short override banner right after each SKILL.md frontmatter,
  3. rewrites the local note paths (~/Documents/notes/, ~/Context/) in the skill's
     Markdown instructions to notes/{YYYY-MM}/ (Tools/ helpers are left alone),
  4. packs every patched skill as dist/<skill>.zip, ready to drag into claude.ai
     (Settings -> Capabilities -> Skills -> Upload). dist/ is git-ignored.

Usage:  python3 scripts/nas/patch.py [--check] [--no-zip]
--check makes no changes and exits 1 if anything still needs patching.
--no-zip skips step 4.
"""
from __future__ import annotations

import re
import shutil
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SKILLS = ROOT / "skills"
CONTRACT = Path(__file__).with_name("NAS_NOTES.md")
DIST = ROOT / "dist"
ZIP_EXCLUDE = {".DS_Store", "node_modules", "__pycache__", ".git"}
# Author-only maintenance tools: they produce no notes, so they are left untouched.
SKIP = {"ljg-push", "fix-ljg-org-to-md"}
# Our own skills already follow the contract natively: copy NAS_NOTES.md, no banner/rewrite.
NATIVE = {"ljg-weekly"}

BEGIN = "<!-- nas-notes:begin (generated by scripts/nas/patch.py; edit NAS_NOTES.md instead) -->"
END = "<!-- nas-notes:end -->"
BANNER = f"""{BEGIN}
> **存储覆盖（本 fork，优先于下文）**：本技能的成品一律存进用户记忆服务器的 `notes/{{YYYY-MM}}/`（MCP 工具 `upsert_memory_file`），不写任何本地笔记目录。下文出现的 `notes/{{YYYY-MM}}/`、`~/Documents/notes/`、`~/Context/` 都指这里。下文写着"默认不保存 / 只在对话中展示"的，本 fork 也要存一份，除非用户说不落盘。Emacs / Denote 读回检查一律跳过。**保存前先读本技能目录里的 `NAS_NOTES.md`**，按它的文件名、文件头和调用规则做。
{END}
"""
BANNER_RE = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n?", re.S)
FRONTMATTER_RE = re.compile(r"\A---\n.*?\n---\n", re.S)
LOCAL_PATH_RE = re.compile(r"(?:~|\$HOME|\$\{HOME\})/(?:Documents/notes|Context)(?![\w-])/?")
TARGET = "notes/{YYYY-MM}/"


def patched_skill_md(text: str) -> str:
    text = BANNER_RE.sub("", text)
    m = FRONTMATTER_RE.match(text)
    if not m:
        return BANNER + "\n" + text.lstrip("\n")
    return text[:m.end()] + "\n" + BANNER + "\n" + text[m.end():].lstrip("\n")


def instruction_files(skill: Path):
    for p in sorted(skill.rglob("*.md")):
        rel = p.relative_to(skill)
        if rel.parts[0] == "Tools" or p.name == "NAS_NOTES.md":
            continue
        yield p


def build_zips(skills: list[Path]) -> list[Path]:
    """One zip per skill, with the skill folder at the zip root (what claude.ai expects)."""
    shutil.rmtree(DIST, ignore_errors=True)
    DIST.mkdir()
    out = []
    for skill in skills:
        dest = DIST / f"{skill.name}.zip"
        with zipfile.ZipFile(dest, "w", zipfile.ZIP_DEFLATED) as z:
            for f in sorted(skill.rglob("*")):
                rel = f.relative_to(skill)
                if f.is_file() and not ZIP_EXCLUDE.intersection(rel.parts):
                    z.write(f, f"{skill.name}/{rel.as_posix()}")
        out.append(dest)
    return out


def main() -> int:
    check = "--check" in sys.argv[1:]
    contract = CONTRACT.read_text(encoding="utf-8")
    pending: list[str] = []

    def put(path: Path, new: str) -> None:
        old = path.read_text(encoding="utf-8") if path.exists() else None
        if old != new:
            pending.append(str(path.relative_to(ROOT)))
            if not check:
                path.write_text(new, encoding="utf-8")

    for skill in sorted(d for d in SKILLS.iterdir() if d.is_dir() and d.name.startswith("ljg-")):
        if skill.name in SKIP:
            continue
        put(skill / "NAS_NOTES.md", contract)
        if skill.name in NATIVE:
            continue
        for f in instruction_files(skill):
            text = f.read_text(encoding="utf-8")
            new = LOCAL_PATH_RE.sub(TARGET, text)
            if f.name == "SKILL.md" and f.parent == skill:
                new = patched_skill_md(new)
            put(f, new)

    leftovers = [str(f.relative_to(ROOT)) for s in SKILLS.glob("ljg-*") if s.name not in SKIP
                 for f in instruction_files(s)
                 if LOCAL_PATH_RE.search(BANNER_RE.sub("", f.read_text(encoding="utf-8")))]
    if check:
        for p in pending:
            print(f"needs patch: {p}")
        return 1 if pending else 0
    print(f"patched {len(pending)} file(s)")
    for p in pending:
        print(f"  {p}")
    if leftovers:
        print("local paths still present in:", *leftovers, sep="\n  ")
        return 1
    if "--no-zip" not in sys.argv[1:]:
        skills = sorted(d for d in SKILLS.iterdir()
                        if d.is_dir() and d.name.startswith("ljg-") and d.name not in SKIP)
        zips = build_zips(skills)
        print(f"zipped {len(zips)} skill(s) into {DIST.relative_to(ROOT)}/ - drag them into claude.ai")
    return 0


if __name__ == "__main__":
    sys.exit(main())
